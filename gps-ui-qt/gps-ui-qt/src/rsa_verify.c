static const unsigned char PUBKEY_E[3] = {0x01, 0x00, 0x01}; /* 65537 */

int rsa_verify(const uint8_t *public_key_der, size_t pubkey_len,
               const uint8_t *signature,
               const uint8_t *message, size_t message_len) {
    (void)public_key_der; (void)pubkey_len; /* embedded key used instead */
    BCRYPT_ALG_HANDLE hAlg = NULL;
    BCRYPT_KEY_HANDLE hKey = NULL;
    int result = 0;

    if (BCryptOpenAlgorithmProvider(&hAlg, BCRYPT_RSA_ALGORITHM, NULL, 0) != 0)
        return 0;

    /* Build BCRYPT_RSAPUBLIC_BLOB: header + exponent + modulus */
    struct {
        ULONG Magic;
        ULONG BitLength;
        ULONG cbPublicExp;
        ULONG cbModulus;
        ULONG cbPrime1;
        ULONG cbPrime2;
    } hdr;
    hdr.Magic = 0x31415352; /* BCRYPT_RSAPUBLIC_MAGIC */
    hdr.BitLength = 2048;
    hdr.cbPublicExp = 3;
    hdr.cbModulus = 256;
    hdr.cbPrime1 = 0;
    hdr.cbPrime2 = 0;

    size_t blobSize = sizeof(hdr) + sizeof(PUBKEY_E) + sizeof(PUBKEY_N);
    uint8_t *blob = (uint8_t*)malloc(blobSize);
    if (!blob) { BCryptCloseAlgorithmProvider(hAlg, 0); return 0; }
    memcpy(blob, &hdr, sizeof(hdr));
    memcpy(blob + sizeof(hdr), PUBKEY_E, sizeof(PUBKEY_E));
    memcpy(blob + sizeof(hdr) + sizeof(PUBKEY_E), PUBKEY_N, sizeof(PUBKEY_N));

    NTSTATUS status = BCryptImportKeyPair(hAlg, NULL, BCRYPT_RSAPUBLIC_BLOB,
                                          &hKey, blob, (ULONG)blobSize, 0);
    free(blob);
    if (status != 0) { BCryptCloseAlgorithmProvider(hAlg, 0); return 0; }

    /* SHA-256 hash of message */
    uint8_t hash[32];
    BCRYPT_ALG_HANDLE hHashAlg = NULL;
    BCRYPT_HASH_HANDLE hHash = NULL;
    if (BCryptOpenAlgorithmProvider(&hHashAlg, BCRYPT_SHA256_ALGORITHM, NULL, 0) != 0)
        goto cleanup;
    if (BCryptCreateHash(hHashAlg, &hHash, NULL, 0, NULL, 0, 0) != 0)
        { BCryptCloseAlgorithmProvider(hHashAlg, 0); goto cleanup; }
    BCryptHashData(hHash, (uint8_t*)message, (ULONG)message_len, 0);
    BCryptFinishHash(hHash, hash, sizeof(hash), 0);
    BCryptDestroyHash(hHash);
    BCryptCloseAlgorithmProvider(hHashAlg, 0);

    BCRYPT_PKCS1_PADDING_INFO padInfo;
    padInfo.pszAlgId = BCRYPT_SHA256_ALGORITHM;

    status = BCryptVerifySignature(hKey, &padInfo, hash, sizeof(hash),
                                    (uint8_t*)signature, 256, BCRYPT_PAD_PKCS1);
    result = (status == 0) ? 1 : 0;

cleanup:
    if (hKey) BCryptDestroyKey(hKey);
    BCryptCloseAlgorithmProvider(hAlg, 0);
    return result;
}
